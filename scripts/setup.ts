// Generates .env.local with fresh Arc TESTNET keys and random secrets.
// Prints addresses only. Refuses to overwrite an existing file.

import { existsSync, writeFileSync, chmodSync } from "node:fs";
import { randomBytes, randomInt } from "node:crypto";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";

const FILE = ".env.local";
if (existsSync(FILE)) {
  console.error(`${FILE} already exists. Delete it first if you really want new keys.`);
  process.exit(1);
}

const wallets = Object.fromEntries(["agent", "sender", "savings", "alice"].map((name) => {
  const key = generatePrivateKey();
  return [name, { key, address: privateKeyToAccount(key).address }];
})) as Record<"agent" | "sender" | "savings" | "alice", { key: `0x${string}`; address: string }>;

// No 1 or 4: both are easy to mishear over a phone line, in English and in Mandarin.
const PIN_DIGITS = "2356789";
const pin = Array.from({ length: 4 }, () => PIN_DIGITS[randomInt(PIN_DIGITS.length)]).join("");
const secret = () => randomBytes(24).toString("base64url");

const env = `# Generated by scripts/setup.ts. Arc TESTNET only. Do not commit.
PER_TX_CAP=50
DAILY_CAP=200
APPROVAL_THRESHOLD=5
GAS_RESERVE_USDC=1
SWEEP_THRESHOLD_USDC=10
SAVINGS_LABEL=savings
ALLOWLIST=savings:${wallets.savings.address},alice:${wallets.alice.address}
ALLOWLIST_ALIASES="savings:储蓄|存款,alice:爱丽丝"

# Set this to your own mobile number in E.164 before starting the server.
OWNER_NUMBERS=
OWNER_PIN=${pin}
OWNER_LANGUAGE=en

HOTLINE_SECRET=${secret()}
DASHBOARD_TOKEN=${secret()}

ARC_RPC_URL=https://rpc.testnet.arc.io
AGENT_PRIVATE_KEY=${wallets.agent.key}

SENDER_PRIVATE_KEY=${wallets.sender.key}
SAVINGS_PRIVATE_KEY=${wallets.savings.key}
ALICE_PRIVATE_KEY=${wallets.alice.key}
`;

writeFileSync(FILE, env, { mode: 0o600 });
chmodSync(FILE, 0o600);

console.log(`Wrote ${FILE} (keys, PIN, and secrets are in the file, not printed here).\n`);
console.log("Testnet addresses:");
for (const [name, w] of Object.entries(wallets)) console.log(`  ${name.padEnd(8)} ${w.address}`);
console.log("\nNext:");
console.log("  1. Fund `sender` (and a little to `agent`) at https://faucet.circle.com, network Arc Testnet.");
console.log("  2. Set OWNER_NUMBERS in .env.local to your mobile number.");
console.log("  3. npm run chain");
