// The filter that runs on QuickNode's servers for our Stream (dataset: logs, network: Arc testnet).
//
// Arc logs every USDC movement as an ERC-20 Transfer from a system address (EIP-7708, 18 decimals).
// The USDC ERC-20 contract logs ERC-20 calls a second time at 6 decimals. Matching only the system
// emitter counts every transfer exactly once, native or ERC-20. The filter turns raw logs into a
// short list of deposits to the agent and returns null otherwise, so most batches deliver nothing.
//
// Plain JavaScript, built as a string because QuickNode runs it, not us. Tested locally in a VM.

import { USDC_SYSTEM_EMITTER } from "../wallet/arc.ts";

const TRANSFER_TOPIC = "0xddf252ad1be2c89b69c2b068fc378daa952ba7f163c4a11628f55a4df523b3ef";

export function buildStreamFilter(agent: string): string {
  const agentTopic = "0x" + agent.toLowerCase().replace(/^0x/, "").padStart(64, "0");
  return `// Hotline deposit filter. Generated by src/deposits/stream-filter.ts; edits here are overwritten.
const EMITTER = ${JSON.stringify(USDC_SYSTEM_EMITTER.toLowerCase())};
const TRANSFER = ${JSON.stringify(TRANSFER_TOPIC)};
const AGENT_TOPIC = ${JSON.stringify(agentTopic)};

function main(stream) {
  const deposits = [];
  const visit = (node) => {
    if (Array.isArray(node)) { for (const child of node) visit(child); return; }
    if (!node || typeof node !== "object" || !Array.isArray(node.topics)) return;
    const topics = node.topics.map((t) => String(t).toLowerCase());
    if (String(node.address).toLowerCase() !== EMITTER) return;
    if (topics.length < 3 || topics[0] !== TRANSFER || topics[2] !== AGENT_TOPIC) return;
    deposits.push({
      tx_hash: node.transactionHash,
      log_index: parseInt(node.logIndex, 16),
      from: "0x" + topics[1].slice(26),
      to: "0x" + topics[2].slice(26),
      value: BigInt(node.data).toString(),
      block_number: parseInt(node.blockNumber, 16),
    });
  };
  visit(stream.data);
  return deposits.length ? { deposits } : null;
}
`;
}
